// Build-time derived-page generator (D-005, T-003).
//
// The "derive — never re-type" half of D-005: rather than duplicate canonical
// reference prose into the site (the drift trap the 2026-07-04 retrospective
// flags), generate it at build time by reading the sibling repo files
// directly:
//   - one skill-reference page per skills/<name>/SKILL.md (name + description)
//   - record-schema pages quoting docs/CONVENTIONS-SPEC.md field lists
//
// Output lands in content/docs/reference/{skills,records}/ and is gitignored
// — the repo files are the single source of truth; these pages are a build
// artifact regenerated on every dev/build (see package.json pre* scripts).
//
// D-005's accepted boundary: a repo *path* move (skills/, docs/CONVENTIONS-
// SPEC.md) breaks this script loudly via a filesystem error — strictly better
// than silent doc drift. Loud failure on intra-file drift (renamed spec
// headings, empty descriptions, skills that don't map one-to-one to pages) is
// the T-004 hardening layered on top of the extraction helpers here.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(siteRoot, '..');
const SKILLS_DIR = path.join(repoRoot, 'skills');
const SPEC_PATH = path.join(repoRoot, 'docs', 'CONVENTIONS-SPEC.md');
const CONTENT_ROOT = path.join(siteRoot, 'content', 'docs');
// The two derived trees land in different D-010 sections: the per-skill pages
// under "The Pipeline" (D-010 §3, T-010) and the record-schema pages under
// "Record Conventions" (D-010 §4, T-011). Each section's authored overview
// lives in the parent dir, which resetDir(<section>/<subdir>) never touches.
const SKILLS_OUT = path.join(CONTENT_ROOT, 'pipeline', 'skills');
const RECORDS_OUT = path.join(CONTENT_ROOT, 'record-conventions', 'records');

const GENERATED_NOTE = (source) =>
  `{/* GENERATED by scripts/generate-derived.mjs from ${source} — do not edit by hand (D-005). */}`;

// --- extraction helpers (T-004 asserts on their outputs) -------------------

// Parse the leading `--- ... ---` YAML frontmatter of a SKILL.md for its
// single-line name + description fields. Returns '' for a field the block
// does not define, so callers (T-004) can fail the build on an empty result.
export function parseSkillFrontmatter(raw) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(raw);
  const block = match ? match[1] : '';
  const field = (key) => {
    const m = new RegExp(`^${key}:\\s*(.+)$`, 'm').exec(block);
    return m ? m[1].trim() : '';
  };
  return { name: field('name'), description: field('description') };
}

// Extract the markdown of a CONVENTIONS-SPEC.md section, located by the exact
// heading text, up to the next heading at the same-or-shallower level.
// Returns '' when the anchor heading is absent (T-004 fails the build on '').
export function extractSpecSection(spec, heading) {
  const lines = spec.split('\n');
  const level = (heading.match(/^#+/) ?? ['#'])[0].length;
  const start = lines.findIndex((l) => l.trim() === heading);
  if (start === -1) return '';
  const body = [];
  for (let i = start + 1; i < lines.length; i++) {
    const h = /^(#+)\s/.exec(lines[i]);
    if (h && h[1].length <= level) break;
    body.push(lines[i]);
  }
  return body.join('\n').trim();
}

// --- generation ------------------------------------------------------------

async function readSkills(skillsDir) {
  const entries = await fs.readdir(skillsDir, { withFileTypes: true });
  const skills = [];
  for (const e of entries) {
    if (!e.isDirectory()) continue;
    const skillPath = path.join(skillsDir, e.name, 'SKILL.md');
    let raw;
    try {
      raw = await fs.readFile(skillPath, 'utf8');
    } catch {
      // A directory without a SKILL.md (e.g. skills/_shared) is not a skill.
      continue;
    }
    const { name, description } = parseSkillFrontmatter(raw);
    skills.push({ slug: e.name, name, description });
  }
  skills.sort((a, b) => a.slug.localeCompare(b.slug));
  return skills;
}

// Loud build failure on intra-file drift (R-002, T-004). D-005 promised
// single-sourcing degrades to a loud build failure, but that only covered a
// path *move*. The build also reads *inside* the files — skill name/
// description, spec section anchors — where a renamed heading, reflowed
// description, or added/removed skill leaves paths intact and would otherwise
// emit a truncated/empty/stale page silently. This error makes every such
// intra-file failure fail the build instead.
export class DerivedDriftError extends Error {
  constructor(problems) {
    super(
      `Derived-page generation aborted — ${problems.length} source-drift problem(s):\n` +
        problems.map((p) => `  - ${p}`).join('\n')
    );
    this.name = 'DerivedDriftError';
    this.problems = problems;
  }
}

function skillPage({ slug, name, description }) {
  const title = name || slug;
  return `---
title: ${JSON.stringify(title)}
description: ${JSON.stringify(description)}
---

${GENERATED_NOTE(`skills/${slug}/SKILL.md`)}

${description}
`;
}

// Quote the spec section as a fenced block so its literal markdown — which
// contains angle-bracket placeholders like \`<Title>\` — is never parsed as
// MDX/JSX. Honestly "quoted verbatim from CONVENTIONS-SPEC.md" (D-005).
function recordPage({ title, section }) {
  return `---
title: ${JSON.stringify(title)}
description: ${JSON.stringify(`Record-schema field list, quoted verbatim from docs/CONVENTIONS-SPEC.md.`)}
---

${GENERATED_NOTE('docs/CONVENTIONS-SPEC.md')}

Quoted verbatim from \`docs/CONVENTIONS-SPEC.md\`:

\`\`\`\`markdown
${section}
\`\`\`\`
`;
}

async function resetDir(dir) {
  await fs.rm(dir, { recursive: true, force: true });
  await fs.mkdir(dir, { recursive: true });
}

const RECORD_TYPES = [
  { slug: 'decisions', title: 'Decision record fields', heading: '### `D-NNN.md` fields (in order)' },
  { slug: 'risks', title: 'Risk record fields', heading: '### `R-NNN.md` fields (in order)' },
  { slug: 'tasks', title: 'Task record fields', heading: '### `T-NNN.md` fields (in order)' },
];

export async function generate(opts = {}) {
  const skillsDir = opts.skillsDir ?? SKILLS_DIR;
  const specPath = opts.specPath ?? SPEC_PATH;
  // The skills and records trees now default to independent roots (D-010).
  // The test harness still passes a single opts.outRoot and expects
  // <outRoot>/{skills,records}, so honor that contract when it is given.
  const skillsOut = opts.skillsOut ?? (opts.outRoot ? path.join(opts.outRoot, 'skills') : SKILLS_OUT);
  const recordsOut =
    opts.recordsOut ?? (opts.outRoot ? path.join(opts.outRoot, 'records') : RECORDS_OUT);

  // Reading these sibling repo files directly is the single-sourcing seam; a
  // moved path throws here and fails the build loudly (D-005).
  const spec = await fs.readFile(specPath, 'utf8');
  const skills = await readSkills(skillsDir);
  const records = RECORD_TYPES.map((t) => ({
    ...t,
    section: extractSpecSection(spec, t.heading),
  }));

  // --- fail loud on intra-file drift BEFORE writing anything (R-002) ---
  const problems = [];
  // (1) every derived skill page must resolve a non-empty name + description.
  for (const s of skills) {
    if (!s.name) problems.push(`skills/${s.slug}/SKILL.md: empty or missing frontmatter \`name\``);
    if (!s.description)
      problems.push(`skills/${s.slug}/SKILL.md: empty or missing frontmatter \`description\``);
  }
  // (2) every required spec section anchor must be present.
  for (const r of records) {
    if (!r.section)
      problems.push(`CONVENTIONS-SPEC.md: required section anchor not found: "${r.heading}"`);
  }
  // Enumeration must be non-empty — an empty skills dir means the anchor moved.
  if (skills.length === 0) problems.push(`no SKILL.md files found under ${skillsDir}`);
  if (problems.length > 0) throw new DerivedDriftError(problems);

  await resetDir(skillsOut);
  for (const skill of skills) {
    await fs.writeFile(path.join(skillsOut, `${skill.slug}.mdx`), skillPage(skill));
  }
  await fs.writeFile(
    path.join(skillsOut, 'meta.json'),
    JSON.stringify({ title: 'Skills', pages: skills.map((s) => s.slug) }, null, 2) + '\n'
  );

  await resetDir(recordsOut);
  for (const rec of records) {
    await fs.writeFile(
      path.join(recordsOut, `${rec.slug}.mdx`),
      recordPage({ title: rec.title, section: rec.section })
    );
  }
  await fs.writeFile(
    path.join(recordsOut, 'meta.json'),
    JSON.stringify({ title: 'Record schema', pages: RECORD_TYPES.map((t) => t.slug) }, null, 2) + '\n'
  );

  // (3) one-to-one: the pages actually on disk must match the enumerated
  // skills exactly — no stale page left behind, no skill that produced none.
  const written = (await fs.readdir(skillsOut))
    .filter((f) => f.endsWith('.mdx'))
    .map((f) => f.replace(/\.mdx$/, ''))
    .sort();
  const enumerated = skills.map((s) => s.slug).sort();
  const onlyOnDisk = written.filter((s) => !enumerated.includes(s));
  const onlyEnumerated = enumerated.filter((s) => !written.includes(s));
  if (onlyOnDisk.length || onlyEnumerated.length) {
    throw new DerivedDriftError([
      `skill pages are not one-to-one with skills/: ` +
        `stale page(s) [${onlyOnDisk.join(', ')}], missing page(s) [${onlyEnumerated.join(', ')}]`,
    ]);
  }

  return { skills, records };
}

// Run when invoked directly (npm pre-scripts); importable for tests (T-004).
if (import.meta.url === `file://${process.argv[1]}`) {
  generate()
    .then(({ skills, records }) =>
      console.log(
        `[generate-derived] ${skills.length} skill pages, ${records.length} record-schema pages`
      )
    )
    .catch((err) => {
      console.error('[generate-derived] failed:', err.message);
      process.exit(1);
    });
}
